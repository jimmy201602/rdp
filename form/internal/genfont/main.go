// genfont extracts the glyphs needed by package form from a GNU Unifont
// .hex file (one "XXXX:HEX" line per code point; 32 hex digits for an
// 8x16 glyph, 64 for a 16x16 glyph) and writes them as Go source.
//
//	go run ./form/internal/genfont -hex unifont.hex -text form/internal/genfont/strings.txt > form/glyphs_unifont.go
package main

import (
	"bufio"
	"bytes"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strconv"
	"strings"
)

func main() {
	hexPath := flag.String("hex", "", "GNU Unifont .hex file")
	textPath := flag.String("text", "", "UTF-8 text whose runes are extracted (ASCII 0x20-0x7E and U+FFFD are always included)")
	version := flag.String("version", "", "Unifont version string recorded in the output")
	flag.Parse()
	if *hexPath == "" || *textPath == "" {
		log.Fatal("-hex and -text are required")
	}
	text, err := os.ReadFile(*textPath)
	if err != nil {
		log.Fatal(err)
	}
	want := map[rune]bool{0xFFFD: true}
	for r := rune(0x20); r <= 0x7E; r++ {
		want[r] = true
	}
	for _, r := range string(text) {
		if r > 0x20 {
			want[r] = true
		}
	}
	f, err := os.Open(*hexPath)
	if err != nil {
		log.Fatal(err)
	}
	defer func() { _ = f.Close() }()
	glyphs := map[rune][]byte{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		cp, bits, ok := strings.Cut(sc.Text(), ":")
		if !ok {
			continue
		}
		v, err := strconv.ParseUint(cp, 16, 32)
		if err != nil || !want[rune(v)] {
			continue
		}
		b, err := hex.DecodeString(strings.TrimSpace(bits))
		if err != nil || (len(b) != 16 && len(b) != 32) {
			log.Fatalf("U+%04X: bad glyph %q", v, bits)
		}
		glyphs[rune(v)] = b
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	runes := make([]rune, 0, len(glyphs))
	for r := range want {
		if _, ok := glyphs[r]; !ok {
			log.Fatalf("U+%04X %q missing from %s", r, string(r), *hexPath)
		}
		runes = append(runes, r)
	}
	sort.Slice(runes, func(i, j int) bool { return runes[i] < runes[j] })
	var buf bytes.Buffer
	w := &buf
	fmt.Fprintf(w, "// Code generated by form/internal/genfont from GNU Unifont %s; DO NOT EDIT.\n", *version)
	fmt.Fprintln(w, "//")
	fmt.Fprintln(w, "// The glyph bitmaps below are a subset of GNU Unifont (Copyright (C)")
	fmt.Fprintln(w, "// 1998-2022 Roman Czyborra, Paul Hardy, Qianqian Fang, Andrew Miller,")
	fmt.Fprintln(w, "// Johnnie Weaver, David Corbett and other contributors), used under the")
	fmt.Fprintln(w, "// SIL Open Font License, Version 1.1 (see OFL-1.1.txt in this directory).")
	fmt.Fprintln(w, "// Unifont is dual-licensed under the OFL 1.1 and the GNU GPL 2+ with the")
	fmt.Fprintln(w, "// font embedding exception; this subset is distributed under the OFL only.")
	fmt.Fprintln(w, "// No Reserved Font Name is used by this program.")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "package form")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "// unifontGlyphs maps a rune to its row-major 1bpp bitmap, 16 rows of 1")
	fmt.Fprintln(w, "// byte (8 px wide) or 2 bytes (16 px wide), most significant bit left.")
	fmt.Fprintln(w, "var unifontGlyphs = map[rune][]byte{")
	for _, r := range runes {
		fmt.Fprintf(w, "\t0x%04X: {", r)
		for i, b := range glyphs[r] {
			if i > 0 {
				w.WriteString(", ")
			}
			fmt.Fprintf(w, "0x%02x", b)
		}
		fmt.Fprintf(w, "}, // %s\n", runeComment(r))
	}
	fmt.Fprintln(w, "}")
	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if _, err := os.Stdout.Write(src); err != nil {
		log.Fatal(err)
	}
}

func runeComment(r rune) string {
	if r < 0x7F {
		return strconv.QuoteRune(r)
	}
	return string(r)
}
